"""ICDE — §8.8/T4 scalability N-sweep driver: OnPair vs Re-Pair on
synthetic V-D columns of N ∈ {10^5..10^8} rows (L=32, sigma=16, rho=0.5),
pre-generated by tools/gen_vd_columns.py.

Per (column × baseline): compress then bulk_decode through the standard NDJSON
protocol, with a hard per-op deadline — a baseline that exceeds it is killed and
recorded as status='timeout' (that IS the scalability result for repair at large
N). Writes build/nsweep_results.sqlite.
"""
from __future__ import annotations
import argparse
import datetime as _dt
import json
import selectors
import sqlite3
import subprocess
import sys
import tempfile
import time
import uuid
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent

CONFIGS = {
    "onpair": ("runners/onpair/onpair_runner",
               {"bits": 16, "sample_fraction": 0.15, "seed": 42, "threads": 1,
                "mem_cap_gb": 64}),
    "repair": ("runners/repair/repair_runner", {"mem_cap_gb": 64}),
}

SCHEMA = """
CREATE TABLE IF NOT EXISTS nsweep_results (
  run_id TEXT, cell_id TEXT PRIMARY KEY, baseline TEXT, n_rows INTEGER,
  input_bytes INTEGER, status TEXT,
  t_compress_ns REAL, t_decode_ns REAL, output_bytes INTEGER,
  dict_bytes REAL, num_rules REAL, peak_rss_bytes INTEGER,
  notes TEXT, ts_utc TEXT
);
"""


def _recv_deadline(proc, sel, deadline: float) -> dict:
    """Read one NDJSON line from proc.stdout, or raise TimeoutError at deadline."""
    buf = ""
    while True:
        remaining = deadline - time.monotonic()
        if remaining <= 0:
            raise TimeoutError
        if not sel.select(timeout=min(remaining, 5.0)):
            continue
        chunk = proc.stdout.readline()
        if chunk == "":
            raise EOFError("runner closed stdout")
        buf += chunk
        if buf.endswith("\n"):
            return json.loads(buf)


def peak_rss_bytes(pid: int) -> int | None:
    try:
        with open(f"/proc/{pid}/status") as f:
            for line in f:
                if line.startswith("VmHWM:"):
                    return int(line.split()[1]) * 1024
    except OSError:
        return None
    return None


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--columns-dir", type=Path,
                    default=REPO_ROOT / "datasets" / "synthetic_vd")
    ap.add_argument("--build-root", type=Path, default=REPO_ROOT / "build")
    ap.add_argument("--db", type=Path,
                    default=REPO_ROOT / "build" / "nsweep_results.sqlite")
    ap.add_argument("--op-timeout-s", type=int, default=2400)
    a = ap.parse_args()

    conn = sqlite3.connect(a.db)
    conn.executescript(SCHEMA)
    run_id = uuid.uuid4().hex
    cols = sorted(a.columns_dir.glob("nsweep__n*.col"),
                  key=lambda p: int(p.stem.split("n")[-1]))
    for col_path in cols:
        n_rows = int(col_path.stem.split("n")[-1])
        for baseline, (rel, cfg) in CONFIGS.items():
            cell_id = f"nsweep-{baseline}-n{n_rows}"
            row = dict(run_id=run_id, cell_id=cell_id, baseline=baseline,
                       n_rows=n_rows, input_bytes=None, status="crash",
                       t_compress_ns=None, t_decode_ns=None, output_bytes=None,
                       dict_bytes=None, num_rules=None, peak_rss_bytes=None,
                       notes="", ts_utc=_dt.datetime.now(
                           _dt.timezone.utc).isoformat())
            with tempfile.TemporaryDirectory() as tmp:
                wire = Path(tmp) / "wire.bin"
                out = Path(tmp) / "out.bin"
                proc = subprocess.Popen(
                    [str(a.build_root / rel)], stdin=subprocess.PIPE,
                    stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                    text=True, bufsize=1,
                    env={"BASELINE_BUILD_FLAGS_SHA": "nsweep",
                         "PATH": "/usr/bin:/bin"})
                sel = selectors.DefaultSelector()
                sel.register(proc.stdout, selectors.EVENT_READ)
                try:
                    hello = _recv_deadline(proc, sel,
                                           time.monotonic() + 30)
                    assert hello.get("type") == "hello"
                    for op, in_p, out_p in (("compress", col_path, wire),
                                            ("bulk_decode", wire, out)):
                        proc.stdin.write(json.dumps({
                            "type": "op", "op": op, "cell_id": cell_id,
                            "input_path": str(in_p), "output_path": str(out_p),
                            "config_json": json.dumps(cfg)}) + "\n")
                        proc.stdin.flush()
                        r = _recv_deadline(
                            proc, sel, time.monotonic() + a.op_timeout_s)
                        st = r.get("status", "crash")
                        m = {x["name"]: x["value"]
                             for x in r.get("metrics", [])}
                        if op == "compress":
                            row["peak_rss_bytes"] = peak_rss_bytes(proc.pid)
                            row["input_bytes"] = m.get("input_bytes")
                            row["t_compress_ns"] = m.get("t_compress_ns")
                            row["output_bytes"] = m.get("output_bytes")
                            row["dict_bytes"] = m.get("dict_bytes")
                            row["num_rules"] = m.get("num_rules")
                        else:
                            row["t_decode_ns"] = m.get("t_decode_ns")
                        if st != "ok":
                            row["status"] = st
                            row["notes"] = f"{op}: {r.get('notes','')}"
                            break
                    else:
                        row["status"] = "ok"
                    proc.stdin.write(json.dumps({"type": "bye"}) + "\n")
                    proc.stdin.flush()
                    proc.wait(timeout=10)
                except TimeoutError:
                    row["status"] = "timeout"
                    row["notes"] = f"op exceeded {a.op_timeout_s}s; killed"
                    row["peak_rss_bytes"] = peak_rss_bytes(proc.pid)
                except Exception as e:  # noqa: BLE001
                    row["notes"] = f"driver error: {e}"
                finally:
                    if proc.poll() is None:
                        proc.kill()
                        proc.wait()
                    sel.close()
            conn.execute(
                "INSERT OR REPLACE INTO nsweep_results VALUES "
                "(:run_id,:cell_id,:baseline,:n_rows,:input_bytes,:status,"
                ":t_compress_ns,:t_decode_ns,:output_bytes,:dict_bytes,"
                ":num_rules,:peak_rss_bytes,:notes,:ts_utc)", row)
            conn.commit()
            print(f"nsweep: {cell_id} -> {row['status']}", flush=True)
    print("nsweep: done")
    return 0


if __name__ == "__main__":
    sys.exit(main())
