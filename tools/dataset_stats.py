"""The paper's dataset-statistics table (Table I), computed from the
materialised columns: number of rows N, size in MiB, share of distinct rows,
average row length L_avg, and LCP_avg, the average longest common prefix
between lexicographically adjacent rows.

Writes T0_datasets.tex and dataset_stats.csv to --out. A column that has not
been materialised is skipped with a note, so the paper stage also runs from
published result stores alone.

Usage: PYTHONPATH=. .venv/bin/python -m tools.dataset_stats \
           [--columns-dir datasets/materialized] [--out build/paper/tables]
"""
from __future__ import annotations
import argparse
import csv
import struct
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent

# (dataset, column file, label in the table)
COLUMNS = [
    ("dbpedia", "abstract.col", "DBpedia"),
    ("msmarco_urls", "url.col", "URLs"),
    ("msmarco_queries", "query.col", "Queries"),
    ("amazon", "titles.col", "Amazon"),
    ("tpch", "p_name.col", "TPC-H p\\_name"),
    ("tpch", "c_comment.col", "TPC-H c\\_comm."),
]


def stats(path: Path) -> dict:
    with open(path, "rb") as f:
        n, total = struct.unpack("<II", f.read(8))
        offsets = struct.unpack(f"<{n + 1}I", f.read((n + 1) * 4))
        data = f.read(total)
    rows = [data[offsets[i]:offsets[i + 1]] for i in range(n)]
    distinct = len(set(rows))
    rows.sort()
    lcp_sum = 0
    for a, b in zip(rows, rows[1:]):
        m = min(len(a), len(b))
        k = 0
        while k < m and a[k] == b[k]:
            k += 1
        lcp_sum += k
    return {"n": n, "bytes": total, "unique_pct": 100.0 * distinct / n,
            "l_avg": total / n, "lcp_avg": lcp_sum / (n - 1) if n > 1 else 0.0}


def table(rows: list[tuple[str, dict]]) -> str:
    lines = [
        "% AUTO-GENERATED by tools/dataset_stats.py — do not edit by hand.",
        "\\begin{table}[t]",
        "  \\centering",
        "  \\caption{Dataset statistics}",
        "  \\label{tab:datasets}",
        "  \\begin{tabular}{lrrrrr}",
        "    \\toprule",
        "    Column & $N$ & MiB & Uniq.\\,\\% & $L_{\\mathrm{avg}}$"
        " & LCP$_{\\mathrm{avg}}$ \\\\",
        "    \\midrule",
    ]
    for label, s in rows:
        lines.append(
            f"    {label} & {s['n'] / 1e6:.2f}M & {s['bytes'] / 2**20:.0f} & "
            f"{s['unique_pct']:.1f} & {s['l_avg']:.0f} & {s['lcp_avg']:.0f} \\\\")
    lines += ["    \\bottomrule", "  \\end{tabular}", "\\end{table}", ""]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--columns-dir", type=Path,
                    default=REPO_ROOT / "datasets" / "materialized")
    ap.add_argument("--out", type=Path,
                    default=REPO_ROOT / "build" / "paper" / "tables")
    a = ap.parse_args()
    rows = []
    for ds, fn, label in COLUMNS:
        path = a.columns_dir / ds / fn
        if not path.exists():
            print(f"dataset_stats: {path} not materialised, skipped")
            continue
        rows.append((label, stats(path)))
        s = rows[-1][1]
        print(f"dataset_stats: {ds}/{fn}: N={s['n']} bytes={s['bytes']} "
              f"unique={s['unique_pct']:.3f}% L_avg={s['l_avg']:.2f} "
              f"LCP_avg={s['lcp_avg']:.2f}", flush=True)
    if not rows:
        print("dataset_stats: no column found; run `./reproduce.sh datasets` first")
        return 0
    a.out.mkdir(parents=True, exist_ok=True)
    (a.out / "T0_datasets.tex").write_text(table(rows))
    with open(a.out / "dataset_stats.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["column", "rows", "bytes", "unique_pct", "l_avg", "lcp_avg"])
        for label, s in rows:
            w.writerow([label.replace("\\", ""), s["n"], s["bytes"],
                        f"{s['unique_pct']:.3f}", f"{s['l_avg']:.2f}",
                        f"{s['lcp_avg']:.2f}"])
    print(f"dataset_stats: wrote {a.out / 'T0_datasets.tex'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
