"""Generate the paper's LaTeX tables and the claims ledger from the result
stores.

Outputs (default --out build/paper/tables):
  T2_throughput.tex   — Table II: ratio, compression and decompression throughput
  T3_access.tex       — Table III: point-access latency, median and p99
  claims_ledger.json  — every number of these tables, keyed by claim id
and three tables with more detail than the paper prints:
  T1_ratio.tex        — the compression ratios alone
  T4_construction.tex — construction time by phase, BPE and OnPair, in seconds
  T5_complete.tex     — compression ratio with row offsets and block
                        directories counted
(Table I comes from tools/dataset_stats.py, T6 from tools/experiments_summary.py.)

Usage:
  PYTHONPATH=. .venv/bin/python -m tools.paper_tables \
      [--build-root build] [--out build/paper/tables]
"""
from __future__ import annotations
import argparse
import json
import sqlite3
import statistics
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent

COLUMNS = [
    ("dbpedia/abstract", "DBpedia"),
    ("msmarco_urls/url", "URLs"),
    ("msmarco_queries/query", "Queries"),
    ("amazon/titles", "Amazon"),
    ("tpch/p_name", "p\\_name"),
    ("tpch/c_comment", "c\\_comm."),
]

BASELINES = [
    ("uncompressed", "\\compressor{Raw}"),
    ("lz4", "\\compressor{LZ4}"),
    ("zstd_l1", "\\compressor{Zstd}-1"),
    ("zstd", "\\compressor{Zstd}-3"),
    ("zstd_l9", "\\compressor{Zstd}-9"),
    ("fsst", "\\compressor{FSST}"),
    ("bpe_v65536", "\\compressor{BPE}"),
    ("rlz", "\\compressor{RLZ}"),
    ("repair", "\\compressor{Re-Pair}"),
    ("onpair", "\\onpair"),
]


def _result_stores(build_root):
    """results.sqlite plus any supplementary results_*.sqlite stores, excluding
    results_turbo* and results_verify* (runs under a different clock setting
    and verification runs, which are not pooled)."""
    stores = [build_root / "results.sqlite"]
    for p in sorted(build_root.glob("results_*.sqlite")):
        if p.name.startswith(("results_turbo", "results_verify")):
            continue
        stores.append(p)
    return [p for p in stores if p.exists()]


def med(conn, dataset, baseline, op, metric):
    # `conn` is a list of connections (results.sqlite + any supplementary
    # stores); rows are unioned before the median.
    conns = conn if isinstance(conn, (list, tuple)) else [conn]
    rows = []
    for c in conns:
        rows += [r[0] for r in c.execute(
            "SELECT metric_value FROM results WHERE dataset=? AND baseline=? "
            "AND op=? AND metric_name=? AND status IN ('ok','dev-only') "
            "AND metric_value IS NOT NULL",
            (dataset, baseline, op, metric))]
    return statistics.median(rows) if rows else None


def ratio(conn, dataset, baseline):
    ib = med(conn, dataset, baseline, "compress", "input_bytes")
    db_ = med(conn, dataset, baseline, "compress", "dict_bytes") or 0.0
    tb = med(conn, dataset, baseline, "compress", "tokens_bytes")
    if ib is None or tb is None:
        return None
    return ib / (db_ + tb)


def throughput_gibs(conn, dataset, baseline, op, tmetric):
    ib = med(conn, dataset, baseline, "compress", "input_bytes")
    t = med(conn, dataset, baseline, op, tmetric)
    if ib is None or t is None or t <= 0:
        return None
    return ib / (t / 1e9) / 2**30


def fmt(v, nd=2, na="--"):
    return na if v is None else f"{v:.{nd}f}"


# Baselines the dictorder stage decodes under both dictionary ID orders, with
# their variant prefix in its results.json.
DICTORDER_CODECS = {"bpe_v65536": "bpe", "onpair": "onpair"}
# Of those, the ones whose own format sorts its ids. Their store number is
# already the sorted-order one, measured like every other row, so the table
# keeps it; BPE's store number uses SentencePiece's own id order.
SORTED_BY_FORMAT = {"onpair"}


def dictorder_decode(build_root):
    """{(dataset, baseline): (sorted-id, frequency-id) decode GiB/s} from the
    dictorder stage; empty on a build without its results.json."""
    path = build_root / "dictorder" / "results.json"
    if not path.exists():
        return {}
    out = {}
    for ds, entry in json.loads(path.read_text())["datasets"].items():
        for b, codec in DICTORDER_CODECS.items():
            out[ds, b] = tuple(
                entry["summary"][f"{codec}_{order}"]["median_gib_per_second"]
                for order in ("lexicographic", "frequency"))
    return out


def gen_t1(conn, out_dir, ledger):
    lines = [
        "% AUTO-GENERATED by tools/paper_tables.py — do not edit by hand.",
        "\\begin{table}[t]",
        "  \\centering",
        "  \\caption{Compression ratio (payload; higher is better)."
        " Medians of repeated runs.}",
        "  \\label{tab:ratio}",
        "  \\small\\setlength{\\tabcolsep}{3.4pt}",
        "  \\begin{tabular}{l" + "r" * len(COLUMNS) + "}",
        "    \\toprule",
        "    & " + " & ".join(lbl for _, lbl in COLUMNS) + " \\\\",
        "    \\midrule",
    ]
    for b, blbl in BASELINES:
        if b == "uncompressed":
            continue
        vals = [ratio(conn, ds, b) for ds, _ in COLUMNS]
        for (ds, _), v in zip(COLUMNS, vals):
            ledger[f"ratio/{ds}/{b}"] = v
        row = f"    {blbl} & " + " & ".join(fmt(v) for v in vals) + " \\\\"
        if b == "onpair":
            lines.append("    \\midrule")
        lines.append(row)
    lines += ["    \\bottomrule", "  \\end{tabular}", "\\end{table}", ""]
    (out_dir / "T1_ratio.tex").write_text("\n".join(lines))


def gen_t2(conn, out_dir, ledger, build_root):
    """The consolidated main table*: per dataset, R (ratio), C (compression
    MiB/s), D (decompression GiB/s). Replaces the former standalone ratio
    pivot. Where the dictorder stage has run, BPE's D cell is that stage's
    number for lexicographically sorted ids, so that BPE and OnPair are
    compared under the same id order; the frequency-order numbers of both go
    to the ledger and the scatter figure only."""
    dictorder = dictorder_decode(build_root)
    split_note = ("; BPE and \\onpair with sorted ids" if dictorder else "")
    lines = [
        "% AUTO-GENERATED by tools/paper_tables.py — do not edit by hand.",
        "\\begin{table*}[t]",
        "  \\centering",
        "  \\caption{Main results: compression ratio (R, payload),"
        " compression throughput (C, MiB/s), and decompression throughput"
        " (D, GiB/s" + split_note + ")}",
        "  \\label{tab:main}",
        "  \\small\\setlength{\\tabcolsep}{2.8pt}",
        # extra glue before each R-C-D group so dataset groups read as units
        "  \\begin{tabular}{l" + "@{\\hskip 11pt}rrr" * len(COLUMNS) + "}",
        "    \\toprule",
        "    & " + " & ".join(f"\\multicolumn{{3}}{{c}}{{{lbl}}}"
                              for _, lbl in COLUMNS) + " \\\\",
        "    " + "".join(
            f"\\cmidrule(lr){{{2+3*i}-{4+3*i}}}" for i in range(len(COLUMNS))),
        "    & " + " & ".join(["R & C & D"] * len(COLUMNS)) + " \\\\",
        "    \\midrule",
    ]
    for b, blbl in BASELINES:
        if b == "uncompressed":
            continue
        cells = []
        for ds, _ in COLUMNS:
            r = ratio(conn, ds, b)
            tc = throughput_gibs(conn, ds, b, "compress", "t_compress_ns")
            td = throughput_gibs(conn, ds, b, "bulk_decode", "t_decode_ns")
            ledger[f"ratio/{ds}/{b}"] = r
            ledger[f"tc_gibs/{ds}/{b}"] = tc
            ledger[f"td_gibs/{ds}/{b}"] = td
            tc_mibs = None if tc is None else tc * 1024
            # one decimal below 10 MiB/s so slow encoders never render as "0";
            # two decimals below 0.5 GiB/s so Re-Pair's decode matches prose
            tc_cell = fmt(tc_mibs, 1 if tc_mibs is not None and tc_mibs < 10 else 0)
            td_cell = fmt(td, 2 if td is not None and td < 0.5 else 1)
            if (ds, b) in dictorder:
                td_sorted, td_freq = dictorder[ds, b]
                ledger[f"td_gibs_sorted/{ds}/{b}"] = td_sorted
                ledger[f"td_gibs_freq/{ds}/{b}"] = td_freq
                if b not in SORTED_BY_FORMAT or td is None:
                    td_cell = fmt(td_sorted, 1)
            cells.append(fmt(r) + " & " + tc_cell + " & " + td_cell)
        if b == "onpair":
            lines.append("    \\midrule")
        lines.append(f"    {blbl} & " + " & ".join(cells) + " \\\\")
    lines += ["    \\bottomrule", "  \\end{tabular}", "\\end{table*}", ""]
    (out_dir / "T2_throughput.tex").write_text("\n".join(lines))


def gen_t3(build_root, out_dir, ledger, results_conn):
    db = build_root / "ra_headline_results.sqlite"
    have = db.exists()
    conn = sqlite3.connect(db) if have else None
    # full-width table*: per dataset a right-aligned p50 column paired with a
    # right-aligned p99 column (comma-separated) so digits line up vertically
    group_spec = "@{\\hskip 10pt}r@{,\\hskip 5pt}r"
    lines = [
        "% AUTO-GENERATED by tools/paper_tables.py — do not edit by hand.",
        "\\begin{table*}[t]",
        "  \\centering",
        "  \\caption{Point-access latency over uniform queries, in ns per"
        " access (median, p99)}",
        "  \\label{tab:access}",
        "  \\footnotesize",
        "  \\begin{tabular}{l" + group_spec * len(COLUMNS) + "}",
        "    \\toprule",
        "    & " + " & ".join(f"\\multicolumn{{2}}{{c}}{{{lbl}}}"
                              for _, lbl in COLUMNS) + " \\\\",
        "    \\midrule",
    ]
    for b, blbl in BASELINES:
        cells = []
        for ds, _ in COLUMNS:
            dsname, col = ds.split("/")
            colname = {"abstract.col": "abstract"}.get(col, col)
            if not have:
                cells.append("-- & --")
                continue
            r = conn.execute(
                "SELECT l_ra_p50_ns, l_ra_p99_ns FROM ra_headline_results "
                "WHERE dataset=? AND column_name=? AND baseline=? "
                "AND status='ok'", (dsname, colname, b)).fetchone()
            if not r or r[0] is None:
                cells.append("-- & --")
                continue
            ledger[f"lra_p50_ns/{ds}/{b}"] = r[0]
            ledger[f"lra_p99_ns/{ds}/{b}"] = r[1]
            p50 = f"{r[0]:,.0f}".replace(",", "\\,")
            p99 = f"{r[1]:,.0f}".replace(",", "\\,")
            cells.append(f"{p50} & {p99}")
        if all(c == "-- & --" for c in cells):
            continue  # baseline not in the RA grid; an all-dash row is noise
        if b == "onpair":
            lines.append("    \\midrule")
        lines.append(f"    {blbl} & " + " & ".join(cells) + " \\\\")
    lines += ["    \\bottomrule", "  \\end{tabular}", "\\end{table*}", ""]
    (out_dir / "T3_access.tex").write_text("\n".join(lines))


def seconds(conn, dataset, baseline, *metrics):
    """Sum of the medians of the given compress-phase timers, in seconds."""
    vals = [med(conn, dataset, baseline, "compress", m) for m in metrics]
    return None if any(v is None for v in vals) else sum(vals) / 1e9


def gen_t4(conn, out_dir, ledger):
    """Construction time by phase for the two size-matched dictionary codecs.
    The totals are the same t_compress_ns behind the C column of the main
    table; training and parsing are the runners' separate phase timers
    (for OnPair, training comes from a standalone probe run, so the two
    phases need not add up exactly to the one-shot total)."""
    phases = [
        ("bpe_v65536", ("t_train_ns",), ("t_encode_ns", "t_pack_ns")),
        ("onpair", ("t_train_ns",), ("t_parse_pack_ns",)),
    ]
    lines = [
        "% AUTO-GENERATED by tools/paper_tables.py — do not edit by hand.",
        "\\begin{table}[t]",
        "  \\centering",
        "  \\caption{Construction time in seconds: training, full-column"
        " parsing, and total}",
        "  \\label{tab:construction}",
        "  \\small\\setlength{\\tabcolsep}{3.4pt}",
        "  \\begin{tabular}{l@{\\hskip 9pt}rrr@{\\hskip 9pt}rrr}",
        "    \\toprule",
        "    & \\multicolumn{3}{c}{\\compressor{BPE}}"
        " & \\multicolumn{3}{c}{\\onpair} \\\\",
        "    \\cmidrule(lr){2-4}\\cmidrule(lr){5-7}",
        "    & train & parse & total & train & parse & total \\\\",
        "    \\midrule",
    ]
    for ds, lbl in COLUMNS:
        cells = []
        for b, train_m, parse_m in phases:
            tr = seconds(conn, ds, b, *train_m)
            pa = seconds(conn, ds, b, *parse_m)
            tot = seconds(conn, ds, b, "t_compress_ns")
            ledger[f"train_s/{ds}/{b}"] = tr
            ledger[f"parse_s/{ds}/{b}"] = pa
            ledger[f"construct_s/{ds}/{b}"] = tot
            cells += [fmt(v, 1 if v is not None and v >= 10 else 2)
                      for v in (tr, pa, tot)]
        lines.append(f"    {lbl} & " + " & ".join(cells) + " \\\\")
    lines += ["    \\bottomrule", "  \\end{tabular}", "\\end{table}", ""]
    (out_dir / "T4_construction.tex").write_text("\n".join(lines))


def gen_t5(conn, out_dir, ledger):
    """Complete-size view: every runner's output_bytes is its accounted
    serialized size, i.e. payload plus the row offsets or block directory that
    the payload-only ratio of the main table leaves out."""
    lines = [
        "% AUTO-GENERATED by tools/paper_tables.py — do not edit by hand.",
        "\\begin{table}[t]",
        "  \\centering",
        "  \\caption{Compression ratio with row and block directories"
        " included}",
        "  \\label{tab:complete}",
        "  \\small\\setlength{\\tabcolsep}{3.4pt}",
        "  \\begin{tabular}{l" + "r" * len(COLUMNS) + "}",
        "    \\toprule",
        "    & " + " & ".join(lbl for _, lbl in COLUMNS) + " \\\\",
        "    \\midrule",
    ]
    for b, blbl in BASELINES:
        if b == "uncompressed":
            continue
        vals = []
        for ds, _ in COLUMNS:
            ib = med(conn, ds, b, "compress", "input_bytes")
            ob = med(conn, ds, b, "compress", "output_bytes")
            v = None if ib is None or not ob else ib / ob
            ledger[f"complete_ratio/{ds}/{b}"] = v
            vals.append(v)
        if b == "onpair":
            lines.append("    \\midrule")
        lines.append(f"    {blbl} & " + " & ".join(fmt(v) for v in vals) + " \\\\")
    lines += ["    \\bottomrule", "  \\end{tabular}", "\\end{table}", ""]
    (out_dir / "T5_complete.tex").write_text("\n".join(lines))


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--build-root", type=Path, default=REPO_ROOT / "build")
    ap.add_argument("--out", type=Path,
                    default=REPO_ROOT / "build" / "paper" / "tables")
    a = ap.parse_args()
    a.out.mkdir(parents=True, exist_ok=True)
    conn = [sqlite3.connect(p) for p in _result_stores(a.build_root)]
    ledger: dict = {}
    gen_t1(conn, a.out, ledger)
    gen_t2(conn, a.out, ledger, a.build_root)
    gen_t3(a.build_root, a.out, ledger, conn)
    gen_t4(conn, a.out, ledger)
    gen_t5(conn, a.out, ledger)
    (a.out / "claims_ledger.json").write_text(
        json.dumps(ledger, indent=1, default=float))
    n = sum(1 for v in ledger.values() if v is not None)
    print(f"paper_tables: wrote T1-T5 + ledger ({n} numbers present)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
